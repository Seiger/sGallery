<?php
declare(strict_types=1);

use Illuminate\Container\Container;
use Illuminate\Support\Facades\Facade;
use Seiger\sGallery\Builders\sGalleryBuilder;
use Seiger\sGallery\Services\NativeImage;

function config($key, $default = null) { return $default; }
function storage_path($path = '') { return EVO_BASE_PATH . 'storage/' . $path; }

require __DIR__ . '/bootstrap.php';

$container = new Container();
Facade::setFacadeApplication($container);
$container->instance('log', new class {
    /** Surface a generation failure in the fixture. @since 1.9.0 */
    public function error(string $message): void
    {
        throw new RuntimeException($message);
    }
});

$gd = NativeImage::canEncode('jpeg', 'gd') && NativeImage::canEncode('png', 'gd');
$imagick = NativeImage::canEncode('jpeg', 'imagick') && NativeImage::canEncode('png', 'imagick');
$exif = function_exists('exif_read_data');
printf("PHP %s, GD %s, Imagick %s, EXIF %s\n", PHP_VERSION,
    $gd ? 'on' : 'off', $imagick ? 'on' : 'off', $exif ? 'on' : 'off');
if (!$gd && !$imagick) {
    echo "SKIP JPEG fixture requires GD or Imagick with JPEG and PNG support\n";
    return;
}

$root = sys_get_temp_dir() . '/sgallery-orientation-' . bin2hex(random_bytes(6)) . '/';
mkdir($root, 0700);
define('EVO_BASE_PATH', $root);
define('EVO_SITE_URL', 'https://images.test/');

$check = static function (bool $ok, string $label): void {
    if (!$ok) {
        throw new RuntimeException($label);
    }
    echo "PASS $label\n";
};

try {
    $spots = [[0, 0, 47, 31], [48, 0, 95, 31], [0, 32, 47, 63], [48, 32, 95, 63]];
    $colors = [[224, 32, 48], [22, 187, 54], [48, 48, 237], [238, 208, 26]];
    $fixture = $root . 'fixture.jpg';
    if ($gd) {
        $frame = imagecreatetruecolor(96, 64);
        foreach ($spots as $index => $rectangle) {
            $color = imagecolorallocate($frame, ...$colors[$index]);
            imagefilledrectangle($frame, ...[...$rectangle, $color]);
        }
        imagejpeg($frame, $fixture, 96);
    } else {
        $frame = new Imagick();
        $frame->newImage(96, 64, 'black', 'JPEG');
        $draw = new ImagickDraw();
        foreach ($spots as $index => $rectangle) {
            $draw->setFillColor(sprintf('#%02x%02x%02x', ...$colors[$index]));
            $draw->rectangle(...$rectangle);
        }
        $frame->drawImage($draw);
        $frame->setImageCompressionQuality(96);
        $frame->writeImage($fixture);
    }
    unset($frame);
    $jpeg = file_get_contents($fixture);
    $tagged = static function (int $orientation) use ($jpeg): string {
        $exif = "Exif\0\0II" . pack('vVv', 42, 8, 1) . pack('vvVVV', 0x0112, 3, 1, $orientation, 0);
        return substr($jpeg, 0, 2) . "\xff\xe1" . pack('n', strlen($exif) + 2) . $exif . substr($jpeg, 2);
    };
    $builder = static fn (string $file): sGalleryBuilder => (new sGalleryBuilder())->file($file)->optimize(false);
    $render = static fn (string $file): string => $builder($file)->fit('max', 96)->format('png')->getFile();
    $path = static fn (string $url): string => $root . rawurldecode(substr($url, strlen(EVO_SITE_URL)));
    $pixel = static function (GdImage|Imagick $frame, int $x, int $y): array {
        $rgba = $frame instanceof GdImage ? imagecolorsforindex($frame, imagecolorat($frame, $x, $y))
            : $frame->getImagePixelColor($x, $y)->getColor();
        return array_slice(array_values($rgba), 0, 3);
    };
    $decodePng = static fn (string $file): GdImage|Imagick => $gd ? imagecreatefrompng($file) : new Imagick($file);
    $matches = static fn (array $pixel, array $color): bool => max(array_map(static fn (int $a, int $b): int => abs($a - $b), $pixel, $color)) < 30;
    $layouts = [
        1 => [0, 1, 2, 3], 2 => [1, 0, 3, 2], 3 => [3, 2, 1, 0], 4 => [2, 3, 0, 1],
        5 => [0, 2, 1, 3], 6 => [2, 0, 3, 1], 7 => [3, 1, 2, 0], 8 => [1, 3, 0, 2],
    ];
    $canOrient = $imagick || ($gd && $exif);
    $oldUrl = null;
    if ($canOrient) {
        // Seed the cache for the stored pixels, as generated by the previous release.
        file_put_contents($root . 'photo-6.jpg', $jpeg);
        $oldUrl = $render('photo-6.jpg');
        $check(array_slice(getimagesize($path($oldUrl)), 0, 3) === [96, 64, IMAGETYPE_PNG], 'Stored-pixel cache seeded');
    }

    foreach ($layouts as $orientation => $layout) {
        $file = "photo-$orientation.jpg";
        file_put_contents($root . $file, $tagged($orientation));
        $url = $render($file);
        [$width, $height] = $canOrient && $orientation >= 5 ? [64, 96] : [96, 64];
        $output = $path($url);
        $info = is_file($output) ? getimagesize($output) : false;
        $check($info !== false && array_slice($info, 0, 3) === [$width, $height, IMAGETYPE_PNG], "Orientation $orientation dimensions");
        if ($imagick) {
            $check(in_array((new Imagick($output))->getImageOrientation(), [0, 1], true),
                "Orientation $orientation PNG does not retain a second EXIF rotation");
        }
        $frame = $decodePng($output);
        $expected = $canOrient ? $layout : $layouts[1];
        $samples = [[12, 12], [$width - 12, 12], [12, $height - 12], [$width - 12, $height - 12]];
        foreach ($samples as $index => [$x, $y]) {
            $check($matches($pixel($frame, $x, $y), $colors[$expected[$index]]), "Orientation $orientation quadrant $index");
        }
    }

    $crop = $path($builder('photo-6.jpg')->crop('topLeft', 24)->format('png')->getFile());
    $check($matches($pixel($decodePng($crop), 8, 8), $colors[$canOrient ? 2 : 0]), 'Crop uses the corrected top-left when orientation is available');
    $check(file_get_contents($root . 'photo-6.jpg') === $tagged(6), 'The source JPEG and its EXIF remain intact');

    if ($oldUrl !== null) {
        $url = $render('photo-6.jpg');
        $output = $path($url);
        $check($url !== $oldUrl && is_file($path($oldUrl)), 'An oriented thumbnail bypasses the old stored-pixel cache');
        touch($output, 1700000000);
        clearstatcache(true, $output);
        $check($render('photo-6.jpg') === $url && filemtime($output) === 1700000000, 'The corrected thumbnail is reused');
        $savedJpeg = $path($builder('photo-6.jpg')->fit('max', 96)->format('jpeg')->getFile());
        $check(array_slice(getimagesize($savedJpeg), 0, 3) === [64, 96, IMAGETYPE_JPEG] &&
            NativeImage::readJpegOrientation($savedJpeg) === 1, 'The JPEG derivative cannot be rotated again by the old tag');

        file_put_contents($root . 'invalid-orientation.jpg', $tagged(9));
        $invalid = $path($render('invalid-orientation.jpg'));
        $check(array_slice(getimagesize($invalid), 0, 3) === [96, 64, IMAGETYPE_PNG], 'An out-of-range tag keeps the stored orientation');

        if ($gd && $imagick) {
            $encoders = new ReflectionProperty(NativeImage::class, 'imagickEncoders');
            $detected = $encoders->getValue();
            try {
                $encoders->setValue(null, [IMAGETYPE_PNG => false] + $detected);
                $fallback = $path($builder('photo-6.jpg')->crop('topLeft', 22)->format('png')->getFile());
                $check($matches($pixel($decodePng($fallback), 8, 8), $colors[2]), 'GD fallback uses the same orientation detected for Imagick');
            } finally {
                $encoders->setValue(null, $detected);
            }
        }
    }
} finally {
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
    foreach ($files as $file) {
        $file->isDir() ? rmdir($file->getPathname()) : unlink($file->getPathname());
    }
    rmdir($root);
}
